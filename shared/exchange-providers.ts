const normalizeCountry = (value: unknown) => String(value ?? "").normalize("NFKD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/\b(the)\b/g, "").replace(/[^a-z0-9]+/g, " ").trim();

export function exchangeProvidersForCountry(country: unknown): ExchangeProvider[] {
  const key = normalizeCountry(country);
  if (!key) return [];
  return exchangeProviders.filter((item) => normalizeCountry(item.country) === key);
}

export function selectRotatingExchangeProvider(country: unknown, rotationSeed: unknown): ExchangeProvider | null {
  const matches = exchangeProvidersForCountry(country);
  if (!matches.length) return null;
  const seed = String(rotationSeed ?? "");
  let hash = 0;
  for (let i = 0; i < seed.length; i += 1) hash = (hash * 31 + seed.charCodeAt(i)) >>> 0;
  return matches[hash % matches.length];
}
